#!/usr/bin/env python3
"""Fit Koren model to EHX 6H30Pi-EB PDF vector curves, not a -DR model.

Coordinate calibration and path identities are specific to the archived PDF.
Transfer curves train/hold out the primary fit; plate curves bound a conflicting alternative.
"""
from pathlib import Path
import csv, hashlib, json
import numpy as np
import pymupdf
from scipy.optimize import least_squares
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]

def groups(path):
    out, group, last = [], [], None
    for kind, a, b in path['items']:
        assert kind == 'l'
        if last is not None and np.linalg.norm(np.array(a)-last) > .01:
            out.append(group); group = []
        group.append((np.array(a),np.array(b))); last = np.array(b)
    return out+[group]

def center_at_y(group, y):
    xs=[]
    for a,b in group:
        if (a[1]<=y<b[1]) or (b[1]<=y<a[1]):
            xs.append(a[0]+(b[0]-a[0])*(y-a[1])/(b[1]-a[1]))
    return (min(xs)+max(xs))/2 if xs else None

def current(vp, vg, p):
    mu, ex, kg, kp, kvb = p
    e=vp/kp*np.logaddexp(0,kp*(1/mu+vg/np.sqrt(kvb+vp*vp)))
    return 2*np.maximum(e,0)**ex/kg

def main():
    source=ROOT/'sources/6H30Pi-EB.pdf'
    pdf=pymupdf.open(source); paths=pdf[2].get_drawings()
    rows=[]
    for n,g in enumerate(groups(paths[110])):
        for vp in np.arange(45,176,5):
            x=center_at_y(g,407.520+vp*(662.639-407.520)/180)
            if x is not None:
                ip=(x-111.839)*(120/(451.918-111.839))/1000
                if ip>.0005: rows.append(('plate',float(vp),float(-2*n),ip))
    for vp,g in zip([160,120,80,60],groups(paths[108])+groups(paths[109])):
        for vg in np.arange(-12.0,-.24,.25):
            x=center_at_y(g,331.440+vg*((331.440-133.199)/14))
            if x is not None:
                ip=(x-111.839)*(120/(451.918-111.839))/1000
                if ip>.0005: rows.append(('transfer',float(vp),float(vg),ip))
    with (ROOT/'models/curve_points.csv').open('w') as f:
        w=csv.writer(f);w.writerow(['family','vp_V','vg_V','ip_A']);w.writerows(rows)
    # Restrict fit to region relevant to this amplifier, retain wider points for audit.
    plate=np.array([r[1:] for r in rows if r[0]=='plate' and 45<=r[1]<=130 and .005<=r[3]<=.070])
    transfer=np.array([r[1:] for r in rows if r[0]=='transfer' and .005<=r[3]<=.070])
    train,hold=transfer[::2],transfer[1::2]
    def residual(p):
        return (current(train[:,0],train[:,1],p)-train[:,2])/np.maximum(train[:,2],.010)
    fit=least_squares(residual,[15,1.4,260,100,1000],bounds=([10,1.1,50,10,1],[22,2,1000,1000,10000]),max_nfev=10000)
    p=fit.x
    metrics={}
    for name,data in [('training',train),('holdout',hold)]:
        err=(current(data[:,0],data[:,1],p)-data[:,2])/data[:,2]
        metrics[name]={'n':len(data),'rms_relative_error':float(np.sqrt(np.mean(err**2))),'max_relative_error':float(abs(err).max())}
    alt=least_squares(lambda q:(current(plate[:,0],plate[:,1],q)-plate[:,2])/np.maximum(plate[:,2],.010),[15,1.4,260,100,1000],bounds=([10,1.1,50,10,1],[22,2,1000,1000,10000]),max_nfev=10000).x
    cross=(current(plate[:,0],plate[:,1],p)-plate[:,2])/plate[:,2]
    metrics.update(parameters=dict(zip(['MU','EX','KG1','KP','KVB'],map(float,p))),
        plate_alternative_parameters=dict(zip(['MU','EX','KG1','KP','KVB'],map(float,alt))),
        cross_family_rms_relative_error=float(np.sqrt(np.mean(cross**2))),
        discrepancy_example={'vp_V':80,'vg_V':-2,'plate_graph_mA':34.27,'transfer_graph_mA':45.41},
        source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
        source_url='https://shop.ehx.com/catalog/tubes-specs/6H30Pi-EB.pdf',
        qualified_for_typical_transfer_curve_estimation=metrics['holdout']['rms_relative_error']<=.10,
        qualified_across_both_official_curve_families=False,
        limitations=['Typical published curves, not measured specimens','Small signal THD sensitivity is not bounded by DC fit residual','No tube noise, microphonics, heater leakage or thermal warmup model','Positive-grid current is an uncalibrated conservative diode approximation'])
    (ROOT/'models/fit_report.json').write_text(json.dumps(metrics,indent=2)+'\n')
    mu,ex,kg,kp,kvb=p
    model=f'''* EHX 6H30Pi-EB, fit to archived official PDF. Generated by scripts/fit_tube.py
* Pins P G K; physical bottle mapping is in circuit.json / schematic.
* W is a scenario emission multiplier, NOT a validated heater model.
.subckt H30 P G K params: SCALE=1 MUS=1 W=1
.param MU={mu:.10g} EX={ex:.10g} KG1={kg:.10g} KP={kp:.10g} KVB={kvb:.10g}
BEP EP 0 V={{max(V(P,K),0)/KP*ln(1+exp(min(80,KP*(1/(MU*MUS)+V(G,K)/sqrt(KVB+V(P,K)^2)))) )}}
BIP P K I={{SCALE*W*2*max(V(EP),0)^EX/KG1}}
RPK P K 1G
RG G GX 2k
DGRID GX K DGRIDMOD
.model DGRIDMOD D(Is=1e-12 N=1.5)
CGK G K 6.3p
CGP G P 6p
CPK P K 2.4p
.ends H30
'''
    (ROOT/'models/6h30pi_eb.lib').write_text(model)
    altmodel=model.replace(f'MU={mu:.10g} EX={ex:.10g} KG1={kg:.10g} KP={kp:.10g} KVB={kvb:.10g}',
        ' '.join(f'{k}={v:.10g}' for k,v in zip(['MU','EX','KG1','KP','KVB'],alt)))
    (ROOT/'models/6h30pi_eb_plate_alternative.lib').write_text(altmodel)
    fig,ax=plt.subplots(figsize=(9,5))
    for vp in [60,80,120,160]:
        d=np.array([r[1:] for r in rows if r[0]=='transfer' and r[1]==vp])
        line=ax.plot(d[:,1],d[:,2]*1000,'o',ms=3,label=f'Vp = {vp} V data')[0]
        v=np.linspace(-12,0,250);ax.plot(v,current(vp,v,p)*1000,color=line.get_color())
    ax.set(xlabel='Grid-cathode voltage (V)',ylabel='Plate current (mA)',ylim=(0,100),title='Official transfer curves (dots) / fitted model (lines)')
    ax.grid(alpha=.25);ax.legend(ncol=2,fontsize=8);fig.tight_layout();fig.savefig(ROOT/'results/model_fit.png',dpi=180)
    print(json.dumps(metrics,indent=2))

if __name__=='__main__':main()
