#!/usr/bin/env python3
"""Fetch selected real devices and preserve library geometry and physical pins.
No topology or drawing is generated by this selection-stage program.
"""
from pathlib import Path
import sys,json,base64,zipfile,io,collections,hashlib,datetime,argparse
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT.parents[1]/'mcp-server'))
from boardspec_mcp.bridge_client import BridgeClient

def parse(text):
 docs={};cur=None
 for line in text.splitlines():
  line=line.rstrip('|')
  if '||' not in line:continue
  h,v=map(json.loads,line.split('||',1))
  if h['type']=='DOCHEAD':cur=docs.setdefault(v['uuid'],{'head':v,'rows':{}})
  elif cur is not None:cur['rows'][(h['type'],h.get('id'))]=(h,v)
 return docs

def main():
 parser=argparse.ArgumentParser();parser.add_argument('--window-id');args=parser.parse_args()
 b=BridgeClient(timeout=90);ws=b.list_windows().get('windows',[])
 if not ws:raise SystemExit('EDA disconnected')
 w=args.window_id or next((x for x in ws if x.get('active')),ws[0])['id'];assert any(v['id']==w for v in ws),'requested window disconnected';selected=json.loads((ROOT/'selection.json').read_text());out=ROOT/'evidence/library/devices';out.mkdir(exist_ok=True)
 lock={'format':'quickpcb-parts-lock/v1','status':'REVIEW_IN_PROGRESS','captured_at':datetime.datetime.now().astimezone().isoformat(),'parts':{}}
 for key,s in selected.items():
  it=s['device'];pid=it['supplierId'];p=out/(pid+'.elibz2')
  if not p.exists():
   code='const f=await eda.sys_FileManager.getDeviceFileByDeviceUuid('+json.dumps(it['uuid'])+','+json.dumps(it['libraryUuid'])+",'elibz2');if(!f)throw Error('missing archive');const a=new Uint8Array(await f.arrayBuffer());let s='';for(let i=0;i<a.length;i+=8192)s+=String.fromCharCode(...a.subarray(i,i+8192));return btoa(s);"
   r=b.execute(code,w)
   if not r.get('ok') or not isinstance(r.get('result'),str):raise RuntimeError((key,r))
   p.write_bytes(base64.b64decode(r['result']))
  with zipfile.ZipFile(p) as z:
   text='|\n'.join(z.read(n).decode() for n in z.namelist() if n.endswith('.elibu'));meta=json.loads(z.read('device2.json'))
  docs=parse(text);symbol=docs[it['symbolUuid']];attrs=collections.defaultdict(dict);pins=[];pads=[]
  for h,v in symbol['rows'].values():
   if h['type']=='ATTR':attrs[v.get('parentId')][v['key']]=v.get('value')
  for h,v in symbol['rows'].values():
   if h['type']=='PIN':pins.append({'primitive_id':h['id'],'part':v.get('partId'),'number':attrs[h['id']].get('Pin Number'),'name':attrs[h['id']].get('Pin Name'),'raw_type':attrs[h['id']].get('Pin Type'),'x':v.get('x'),'y':v.get('y'),'rotation':v.get('rotation'),'length':v.get('length')})
  fp=docs.get(it.get('footprintUuid'))
  if fp:
   for h,v in fp['rows'].values():
    if h['type']=='PAD':pads.append(v)
  entry={**s,'library_uuid':it['libraryUuid'],'device_uuid':it['uuid'],'symbol_uuid':it['symbolUuid'],'footprint_uuid':it.get('footprintUuid'),'manufacturer':it.get('manufacturer'),'mpn':it.get('manufacturerId'),'lcsc':pid,'pins':pins,'pads':pads,'archive':str(p.relative_to(ROOT)),'archive_sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'datasheet_url':it.get('otherProperty',{}).get('Datasheet'),'review':{'status':'PIN_AND_RATING_REVIEW_REQUIRED','electrical_types_preserved':True,'unresolved_types':sorted({x['raw_type'] or 'Missing' for x in pins if x['raw_type'] in [None,'Undefined']})}}
  del entry['device'];entry['library_properties']=it.get('otherProperty',{});entry['library_description']=it.get('description');lock['parts'][key]=entry
  (ROOT/'parts.lock.json').write_text(json.dumps(lock,ensure_ascii=False,indent=2)+'\n')
  print(key,pid,it['name'],[(x['number'],x['name'],x['raw_type']) for x in pins],flush=True)
 print('Captured',len(lock['parts']),'candidate part types. Not yet approved for topology.')
if __name__=='__main__':main()
